/** How many participants the table holds. */
export const participantCount = Object.keys(participants).length;

/** The participant a Turkish IBAN's five-digit bank code names, or null when the lists do not have it. */
export function bankName(code: string): string | null {
  if (!/^0[0-9]{4}$/.test(code)) return null;
  return Object.hasOwn(participants, code.slice(1)) ? participants[code.slice(1)] : null;
}
